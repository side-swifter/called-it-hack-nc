/// Shared scaffold: Aero wallpaper, back button + title, scrolling body fed from appState.
class _Page extends StatelessWidget {
  const _Page({required this.title, required this.builder, this.variant = 0});
  final String title;
  final int variant;
  final Widget Function(BuildContext, Snapshot) builder;

  @override
  Widget build(BuildContext context) => Scaffold(
        body: AeroBackground(
          variant: variant,
          child: ListenableBuilder(
            listenable: appState,
            builder: (context, _) {
              final snap = appState.snap;
              return Column(children: [
                Padding(
                  padding: const EdgeInsets.fromLTRB(12, 8, 12, 8),
                  child: Glass(
                    padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 10),
                    child: Row(children: [
                      GestureDetector(
                        onTap: () => Navigator.of(context).maybePop(),
                        child: Container(
                          width: 36,
                          height: 36,
                          decoration: BoxDecoration(shape: BoxShape.circle, gradient: const LinearGradient(begin: Alignment.topCenter, end: Alignment.bottomCenter, colors: [Color(0xFF45B8F5), Aero.skyDeep]), border: Border.all(color: Colors.white, width: 1.5)),
                          child: const Icon(Icons.arrow_back_ios_new, size: 16, color: Colors.white),
                        ),
                      ),
                      const SizedBox(width: 12),
                      Expanded(child: Text(title, style: const TextStyle(fontSize: 18, fontWeight: FontWeight.w800, color: Aero.ink))),
                      const Pill('CalledIt'),
                    ]),
                  ),
                ),
                if (appState.error != null)
                  const Padding(
                    padding: EdgeInsets.only(bottom: 6),
                    child: Pill('Showing last confirmed data', color: Aero.orange),
                  ),
                Expanded(
                  child: snap == null
                      ? const Center(child: CircularProgressIndicator())
                      : ListView(padding: const EdgeInsets.fromLTRB(12, 0, 12, 16), children: [builder(context, snap)]),
                ),
              ]);
            },
          ),
        ),
      );
}

Prediction? _find(Snapshot s, String? id) {
  final p = s.prediction;
  return (p != null && (id == null || p.id == id)) ? p : null;
}

void _toast(BuildContext c, String m) => ScaffoldMessenger.of(c).showSnackBar(SnackBar(content: Text(m)));

/// Small caps section label, like "PERSONAL SANDBOX BALANCE" in the mockups.
Widget _label(String t) => Text(t.toUpperCase(), style: const TextStyle(fontSize: 11, fontWeight: FontWeight.w800, letterSpacing: .8, color: Aero.inkSoft));

Widget _empty(String text) => Glass(child: Center(child: Padding(padding: const EdgeInsets.all(12), child: Text(text, textAlign: TextAlign.center))));

class InsightsScreen extends StatefulWidget {
  const InsightsScreen({super.key, this.predictionId});
  final String? predictionId;
  @override
  State<InsightsScreen> createState() => _InsightsState();
}

class _InsightsState extends State<InsightsScreen> {
  bool reasoning = false, context_ = false;

  @override
  Widget build(BuildContext context) => _Page(
        title: 'AI Insights',
        builder: (c, snap) {
          final p = _find(snap, widget.predictionId);
          if (p == null) return _empty('No prediction to explain yet.');
          // Regeneration must never replace a live question after people have participated.
          final canRegen = snap.me.isHost && p.picks.isEmpty && (p.stage == 'draft' || p.stage == 'awaiting_approval');
          final regen = appState.busy.contains('regen');
          return Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
            Glass(
              child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                _label('Prediction'),
                const SizedBox(height: 6),
                Text('“${p.question}”', style: const TextStyle(fontSize: 18, fontWeight: FontWeight.w800)),
                const SizedBox(height: 12),
                Wrap(spacing: 8, runSpacing: 6, children: [
                  Pill('YES ${p.yesPct}% (illustrative)', color: Aero.yes),
                  Pill('NO ${p.noPct}% (illustrative)', color: Aero.no),
                  Pill('Generated by ${p.source.isEmpty ? 'unknown' : p.source}'),
                ]),
                const SizedBox(height: 8),
                const Text('Estimates are AI guesses, not validated probabilities.', style: TextStyle(fontSize: 12, color: Aero.inkSoft)),
              ]),
            ),
            const SizedBox(height: 12),
            Glass(
              child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                _label('Observed pattern'),
                const SizedBox(height: 6),
                Text(p.reasoning.isEmpty ? 'No reasoning was recorded for this prediction.' : p.reasoning),
              ]),
            ),
            const SizedBox(height: 12),
            GlossyButton(label: reasoning ? 'Hide Reasoning' : 'View Reasoning', icon: Icons.psychology_outlined, onPressed: () => setState(() => reasoning = !reasoning)),
            if (reasoning) ...[
              const SizedBox(height: 8),
              Glass(child: Text(p.reasoning.isEmpty ? 'Nothing more to show.' : p.reasoning)),
            ],
            const SizedBox(height: 10),
            GlossyButton(label: context_ ? 'Hide Relevant Context' : 'View Relevant Context', icon: Icons.forum_outlined, onPressed: () => setState(() => context_ = !context_)),
            if (context_) ...[
              const SizedBox(height: 8),
              Glass(
                child: snap.messages.where((m) => !m.isAgent).isEmpty
                    ? const Text('No permitted messages are available.')
                    : Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                        for (final m in snap.messages.where((m) => !m.isAgent).toList().reversed.take(5).toList().reversed)
                          Padding(padding: const EdgeInsets.symmetric(vertical: 3), child: Text('${m.sender}: ${m.text}')),
                      ]),
              ),
            ],
            if (canRegen) ...[
              const SizedBox(height: 10),
              GlossyButton(
                label: 'Regenerate Prediction',
                icon: Icons.refresh,
                color: Aero.orange,
                loading: regen,
                onPressed: () async {
                  final e = await appState.post('regen', '/api/demo/generate');
                  if (c.mounted) _toast(c, e ?? 'Prediction regenerated.');
                },
              ),
            ],
            const SizedBox(height: 10),
            GlossyButton(label: 'Back to Prediction', icon: Icons.arrow_back, color: Aero.skyDeep, onPressed: () => Navigator.of(c).maybePop()),
          ]);
        },
      );
}

class PredictionDetailsScreen extends StatelessWidget {
  const PredictionDetailsScreen({super.key, this.predictionId});
  final String? predictionId;

  static String stageLabel(String s) => switch (s) {
        'draft' => 'Draft',
        'awaiting_approval' => 'Awaiting approval',
        'open' => 'Open',
        'locked' => 'Locked',
        'awaiting_outcome' => 'Awaiting outcome',
        'settling' => 'Settling',
        'settled' => 'Settled',
        'settlement_error' => 'Settlement error',
        'cancelled' => 'Cancelled',
        _ => s,
      };

  @override
  Widget build(BuildContext context) => _Page(
        title: 'Prediction Details',
        builder: (c, snap) {
          final p = _find(snap, predictionId);
          if (p == null) return _empty('Prediction not found.');
          return Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
            Glass(
              child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                Text('“${p.question}”', style: const TextStyle(fontSize: 18, fontWeight: FontWeight.w800)),
                const SizedBox(height: 10),
                Wrap(spacing: 8, runSpacing: 6, children: [
                  Pill(stageLabel(p.stage), dot: true),
                  Pill('YES ${p.yesPct}%', color: Aero.yes),
                  Pill('NO ${p.noPct}%', color: Aero.no),
                  Pill('${p.entryAmount} demo chips per pick', color: Aero.inkSoft),
                ]),
              ]),
            ),
            const SizedBox(height: 12),
            Glass(
              child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                Row(children: [
                  Expanded(child: _label('Picks')),
                  Pill('Pool: ${p.pool} chips', color: Aero.gold),
                ]),
                const SizedBox(height: 8),
                if (p.picks.isEmpty) const Text('No picks yet.'),
                for (final k in p.picks)
                  Padding(
                    padding: const EdgeInsets.symmetric(vertical: 4),
                    child: Row(children: [
                      Avatar(k.name, size: 28),
                      const SizedBox(width: 8),
                      Expanded(child: Text(k.name, style: const TextStyle(fontWeight: FontWeight.w700))),
                      if (k.status != 'confirmed') Padding(padding: const EdgeInsets.only(right: 6), child: Pill(k.status == 'pending' ? 'Pending' : 'Not recorded', color: Aero.orange)),
                      Pill('${k.amount} → ${k.choice}', color: k.choice == 'YES' ? Aero.yes : Aero.no),
                    ]),
                  ),
              ]),
            ),
            const SizedBox(height: 12),
            GlossyButton(label: 'Why this prediction?', icon: Icons.lightbulb_outline, onPressed: () => Navigator.of(c).pushNamed('/insights', arguments: p.id)),
            if (snap.result?.predictionId == p.id) ...[
              const SizedBox(height: 10),
              GlossyButton(label: 'View Result', icon: Icons.emoji_events_outlined, color: Aero.grass, onPressed: () => Navigator.of(c).pushNamed('/result', arguments: p.id)),
            ],
          ]);
        },
      );
}

class SettingsScreen extends StatefulWidget {
  const SettingsScreen({super.key});
  @override
  State<SettingsScreen> createState() => _SettingsState();
}

class _SettingsState extends State<SettingsScreen> {
  bool notifications = true; // local preference only

  Widget _status(String name, String state) {
    final color = switch (state) { 'connected' => Aero.grass, 'connecting' => Aero.orange, _ => Colors.redAccent };
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 4),
      child: Row(children: [
        Expanded(child: Text(name, style: const TextStyle(fontWeight: FontWeight.w700))),
        Pill(state[0].toUpperCase() + state.substring(1), color: color, dot: true),
      ]),
    );
  }

  Widget _section(String title, List<Widget> kids) => Padding(
        padding: const EdgeInsets.only(bottom: 12),
        child: Glass(child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [_label(title), const SizedBox(height: 8), ...kids])),
      );

  @override
  Widget build(BuildContext context) => _Page(
        title: 'Settings',
        builder: (c, snap) {
          final me = snap.me;
          return Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
            _section('Profile', [
              Row(children: [
                Avatar(me.name, size: 44),
                const SizedBox(width: 12),
                Expanded(child: Text(me.name.isEmpty ? 'Player' : me.name, style: const TextStyle(fontSize: 17, fontWeight: FontWeight.w800))),
                if (me.isHost) const Pill('Stage Host', color: Aero.skyDeep),
              ]),
              const SizedBox(height: 8),
              Text('${me.balance} demo chips · no cash value'),
            ]),
            _section('Connected room', [
              Text(snap.room.name, style: const TextStyle(fontWeight: FontWeight.w700)),
              Text('${snap.room.membersOnline} members online'),
            ]),
            _section('Integrations', [
              _status('Photon', snap.room.photon),
              _status('Snowflake', snap.room.snowflake),
              _status('Capital One Nessie', snap.room.nessie),
            ]),
            _section('Consent', [
              const Text('The AI companion only reads messages from people in this group chat who opted in. It uses them to suggest harmless predictions. You can leave the group at any time to stop analysis.'),
            ]),
            _section('Notifications', [
              SwitchListTile(activeTrackColor: Aero.sky, contentPadding: EdgeInsets.zero, title: const Text('Prediction and result alerts'), value: notifications, onChanged: (v) => setState(() => notifications = v)),
            ]),
            _section('Demo information', [
              const Text('CalledIt uses free fictional chips with no cash value. Balances are recorded in the Capital One Nessie sandbox.'),
            ]),
            if (me.isHost) GlossyButton(label: 'Host Controls', icon: Icons.tune, onPressed: () => Navigator.of(c).pushNamed('/host')),
          ]);
        },
      );
}

class GreenMomentsScreen extends StatefulWidget {
  const GreenMomentsScreen({super.key});
  @override
  State<GreenMomentsScreen> createState() => _GreenState();
}

class _GreenState extends State<GreenMomentsScreen> {
  static const topics = ['Reusable bottles', 'Recycling station', 'Walk or bike to the meetup'];
  String topic = topics.first;
  bool started = false;

  @override
  Widget build(BuildContext context) => _Page(
        title: 'Green Moments',
        variant: 1,
        builder: (c, snap) {
          final isHost = snap.me.isHost;
          final gen = appState.busy.contains('green');
          final green = snap.activity.where((a) => a.text.toLowerCase().contains('green')).toList();
          return Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
            Glass(
              child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                const Text('Optional: predictions about positive everyday habits, such as “Will everyone bring a reusable bottle to the next meeting?” Same chips, same flow, just a friendlier topic.'),
                const SizedBox(height: 10),
                Wrap(spacing: 8, runSpacing: 6, children: [
                  for (final t in topics) ChoiceChip(label: Text(t), selected: topic == t, onSelected: (_) => setState(() => topic = t)),
                ]),
              ]),
            ),
            const SizedBox(height: 12),
            GlossyButton(label: started ? 'Green Moment Started' : 'Start Green Moment', icon: Icons.eco_outlined, color: Aero.grass, onPressed: started ? null : () => setState(() => started = true)),
            const SizedBox(height: 10),
            GlossyButton(
              label: 'Generate Suggestion',
              icon: Icons.auto_awesome,
              loading: gen,
              onPressed: (!started || !isHost)
                  ? null
                  : () async {
                      final e = await appState.post('green', '/api/demo/generate', {'topic': topic, 'category': 'green'});
                      if (c.mounted) _toast(c, e ?? 'Suggestion created. The host reviews it before it goes live.');
                    },
            ),
            if (!isHost)
              const Padding(padding: EdgeInsets.only(top: 6), child: Text('Only the host can generate suggestions.', textAlign: TextAlign.center, style: TextStyle(fontSize: 12))),
            const SizedBox(height: 12),
            Glass(
              child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                _label('Green activity'),
                const SizedBox(height: 6),
                if (green.isEmpty) const Text('No Green Moments yet.'),
                for (final a in green) Padding(padding: const EdgeInsets.symmetric(vertical: 3), child: Text(a.text)),
              ]),
            ),
          ]);
        },
      );
}
